  /// Returns all locations for a specific country
  static List<LocationModel> getLocationsForCountry(String country) {
    return allLocations.where((l) => l.country == country).toList();
  }

  /// Backward-compatible alias
  static List<LocationModel> getCitiesForCountry(String country) {
    return getLocationsForCountry(country);
  }

  /// Returns location matching country and city or governorate
  static LocationModel getLocation(String country, String city, [String? governorate]) {
    if (governorate != null && governorate.isNotEmpty) {
      final matchGov = allLocations.firstWhere(
        (l) => l.country == country && (l.governorate == governorate || l.city == city),
        orElse: () => allLocations.firstWhere(
          (l) => l.country == country && l.city == city,
          orElse: () => allLocations.firstWhere(
            (l) => l.country == country,
            orElse: () => allLocations.first, // Default Cairo
          ),
        ),
      );
      return matchGov;
    }

    return allLocations.firstWhere(
      (l) => l.country == country && (l.city == city || l.governorate == city),
      orElse: () => allLocations.firstWhere(
        (l) => l.country == country,
        orElse: () => allLocations.first, // Default Cairo
      ),
    );
  }
